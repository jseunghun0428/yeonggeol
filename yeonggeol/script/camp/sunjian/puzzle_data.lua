local DIR={{1,0},{-1,0},{0,1},{0,-1}}
local function pass(x,y) return x>=0 and y>=0 and x<War.Width and y<War.Depth and not BAD[GetWarMap(x+1,y+1,1)] end
-- (tx,ty) 까지 길 거리 (지형만 봄)
local function distMap(tx,ty)
	local W=War.Width local D={[ty*W+tx]=0} local q={{tx,ty}} local h=1
	while h<=#q do
		local c=q[h] h=h+1
		local d=D[c[2]*W+c[1]]
		for _,o in ipairs(DIR) do local nx,ny=c[1]+o[1],c[2]+o[2] if pass(nx,ny) and not D[ny*W+nx] then D[ny*W+nx]=d+1 q[#q+1]={nx,ny} end end
	end
	return D
end
local function chase(pid,D,n,stop)   -- 길을 따라 n칸 (거리 stop 에 닿으면 멈춤, 기본 1 = 바로 옆)
	local W=War.Width
	stop=stop or 1
	local side=false
	for _=1,n do
		local x,y=L.at(pid) if not x then return end
		local cd=D[y*W+x] or 999
		if cd<=stop then return end
		local best,bd=nil,cd
		for _,o in ipairs(DIR) do local nx,ny=x+o[1],y+o[2] local d=D[ny*W+nx] if d and d<bd and L.free(nx,ny) then best,bd={nx,ny},d end end
		if not best and not side then   -- 막혔으면 한 번만 옆으로 비켜 돌아감 (거리가 같은 칸)
			for _,o in ipairs(DIR) do local nx,ny=x+o[1],y+o[2] if not best and D[ny*W+nx]==cd and L.free(nx,ny) then best={nx,ny} side=true end end
		end
		if not best then return end
		L.tp(pid,best[1],best[2])
	end
end
