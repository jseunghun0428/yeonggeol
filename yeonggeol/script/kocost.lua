koCost.score=function(t)
local K=koCost.k
local an=nz(curve(t.wl),K.atkMin,K.atkMax)
local dn=nz(curve(t.ts),K.defMin,K.defMax)
local gn=nz(curve(t.zl),K.magMin,K.magMax)
local phys=0.62*an+0.38*dn
local magi=0.62*gn+0.38*dn
local hi,lo=phys,magi
if magi>phys then hi,lo=magi,phys end
local stat=hi+0.18*lo
local ex=koCost.unlock[t.grow] or {99,99,99,99,99,99}
local raw=0
if t.tf~=nil and t.tf>0 then
raw=raw+(koCost.star[t.tf] or 3)^1.25
end
if t.sk~=nil then
for i=1,6 do
local s=t.sk[i]
if s~=nil and s>0 then
raw=raw+((koCost.star[s] or 3)^1.25)*koCost.uw(ex[i] or 99)
end
end
end
local skn=nz(raw,K.skMin,K.skMax)
local bzn=0.4
if t.bz~=nil then
local b=t.bz
bzn=nz(0.40*b.atk+0.30*b.def+0.15*(b.mov*22)+0.15*(b.rng*14)+0.10*(b.hp/10+b.hpg*2),K.bzMin,K.bzMax)
end
return 0.50*nz(stat,K.stMin,K.stMax)+0.38*skn+0.12*bzn, stat
end
koCost.derive=function(t)
local sc,stat=koCost.score(t)
local c=1
if sc>=0.72 then c=10
elseif sc>=0.65 then c=9
elseif sc>=0.60 then c=8
elseif sc>=0.55 then c=7
elseif sc>=0.50 then c=6
elseif sc>=0.44 then c=5
elseif sc>=0.40 then c=4
elseif sc>=0.33 then c=3
elseif sc>=0.26 then c=2
end
local fl=1
if stat>=0.80 then fl=7
elseif stat>=0.72 then fl=6
elseif stat>=0.62 then fl=5
elseif stat>=0.53 then fl=4
elseif stat>=0.45 then fl=3
elseif stat>=0.30 then fl=2
end
if fl>c then c=fl end
return c
end

-- [7] 예산 = 자유 출진칸 1칸당 허용 코스트
--     0 없음 / 1 여유 / 2 보통 / 3 엄격
--     계수는 전투 64개 배낭 시뮬레이션으로 맞췄다. "제한 없이 최강 조합을 짰을 때 대비
--     전력 유지율" 이 여유 96% / 보통 90% / 엄격 81% 가 되는 값이다.
--     초판은 7.0/5.5/4.2 였는데 7.0 은 거의 모든 전투에서 100% 라 제한이 아니었다.
--     (3.2) 칸 초과 출전(over)이 들어오면서 여유만 6.0 -> 5.5 로 내렸다. 6.0 이면 초과까지 더해
--     여유가 전력 100.0% 에 인원까지 더 많아 "코스트 모드를 켜는 쪽이 무조건 이득" 이 되기 때문.
--     5.5 에서 여유 95.3% / 보통 90.0% / 엄격 79.8% (평균 출전 9.6 / 9.1 / 8.3 명, 칸 평균 8.0).
koCost.rate={[0]=0,[1]=5.5,[2]=5.0,[3]=4.0}
koCost.min=1     -- 아군 최저 코스트
koCost.max=10    -- 아군 최고 코스트

-- (3.2) 칸 초과 출전 : 전장의 자유 출진칸을 넘겨 데려가면 코스트가 더 붙는다.
--     붙는 값은 누진이고 여기서 멈춘다 - 초과 1명째 +1, 2명째 +2, 3명째부터 계속 +3.
--     칸이 희소해서 강한 무장을 쓰는 것인데 칸을 그냥 풀면 "싼 무장 스팸" 이 정답이 되어 버린다
--     (코스트 1~10 사이에 점수는 0.11~0.78, 코스트당 전력은 싼 쪽이 항상 유리하다).
--     배수(x1.5, x2)로 매기면 코스트당 전력 순위가 그대로라 초과 자리도 싼 무장이 정답이 된다.
--     정액이라야 순위가 뒤집혀(간옹 0.247/5=0.049 < 관우 0.744/13=0.057) 섞어 고르는 구간이 생긴다.
--     누진으로 앞쪽을 싸게 한 것은 "총량이 조금 남았는데 한 명 더" 를 막지 않기 위해서다.
--     초과 k명의 추가 비용 합계는 1,3,6,9,12 ... 로 순서와 무관하다.
koCost.over=3

-- slots : 이번 전투에서 플레이어가 직접 고를 수 있는 칸 수 (강제 출진 장수는 제외)
-- level : 기능설정의 코스트 단계 (0=없음)
-- 반환   : 총 예산. 0 이면 제한 없음
koCost.budget=function(slots,level,costs)
level=level or 0
if level<1 or level>3 then return 0 end
if slots==nil or slots<1 then return 0 end
local b=math.floor(slots*koCost.rate[level]+0.5)
-- 하한 1 : 최고 코스트 1명은 항상 담을 수 있게
if b<koCost.max then b=koCost.max end
-- 하한 2 : 가진 무장 중 싼 쪽부터 slots 명은 항상 채울 수 있게.
--          코스트는 "누구를 담을지" 를 고민시키는 장치이지 칸을 비우게 만드는 장치가 아니다.
--          costs 는 선택 가능한(강제 출진이 아닌) 아군의 코스트 배열.
if costs~=nil and #costs>0 then
local t={}
for i,v in ipairs(costs) do t[i]=v end
table.sort(t)
local n=slots
if n>#t then n=#t end
local fl=0
for i=1,n do fl=fl+t[i] end
if b<fl then b=fl end
end
return b
end

-- 단계 표시용 (라벨은 jymain.lua 쪽에서 게임 인코딩으로 그린다)
-- 1 여유 / 2 보통 / 3 엄격

-- [8] 최종 조회
--     pid : JY.Person 인덱스
--     t   : 표에 없을 때 쓸 능력치 묶음 (nil 이면 기본값 3)
koCost.of=function(pid,t)
local c=koCost.fixed[pid]
if c~=nil then return c end
if t==nil then return 3 end
return koCost.derive(t)
end

-- [9] 칸 초과 출전 자리 찾기 (3.2)
--     전장의 출진 자리 주변에서, 그 병종이 설 수 있는 빈 칸을 하나 돌려준다. 없으면 nil.
--     seeds : {{x,y},...} 이미 정해진 출진 좌표(1 기준). taken : 이미 쓴 자리 [y*1000+x]=true
--     지형 판정은 jymain.lua 의 War_CanMoveXY 와 같게 한다(병종의 "地形N" 이 0 이면 못 선다).
--     이 파일은 게임 인코딩 문자열을 쓰지 않으므로 필드 이름만 바이트로 적는다.
koCost.spot=function(bz,taken,seeds)
  local F_TERR=string.char(181,216,208,206) -- 地形
  local b=JY.Bingzhong[bz]
  if b==nil then return nil end
  local W,D=War.Width,War.Depth
  if W==nil or D==nil then return nil end
  local q,seen,head={},{},1
  for _,s in ipairs(seeds) do
    q[#q+1]={s[1],s[2],0}
    seen[s[2]*1000+s[1]]=true
  end
  while head<=#q do
    local c=q[head] head=head+1
    local x,y,dist=c[1],c[2],c[3]
    if dist>0 and not taken[y*1000+x] then
      if b[F_TERR..GetWarMap(x,y,1)]~=0 then return x,y end
    end
    if dist<5 then
      local d={{1,0},{-1,0},{0,1},{0,-1}}
      for i=1,4 do
        local nx,ny=x+d[i][1],y+d[i][2]
        local k=ny*1000+nx
        if nx>=1 and ny>=1 and nx<=W and ny<=D and not seen[k] then
          seen[k]=true
          q[#q+1]={nx,ny,dist+1}
        end
      end
    end
  end
  return nil
end
