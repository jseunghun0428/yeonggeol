-- " \161\164 " 로 이은 목표를 한 줄씩 (줄바꿈 *), 앞에 □, done[i] 면 ■ (달성해도 줄 길이 그대로 — 10-07 사용자)
function koBonusFmt(s,done)
local t={"\131\115\129\072\131\126 \131\099\133\113"}
local sep=" \161\164 "
local p,i=1,0
while true do
local a,b=string.find(s,sep,p,true)
i=i+1
local item=string.sub(s,p,(a or 0)-1)
local m=done and done[i]
t[#t+1]=((m=="x") and "\161\193 " or (m and "\161\246 " or "\161\245 "))..item-- 6.0 (11-03): "x" = 이야기 모드에서 이미 못 이룬 목표
if not a then break end
p=b+1
end
return table.concat(t,"*")
end
