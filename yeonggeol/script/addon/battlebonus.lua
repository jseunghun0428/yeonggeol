local rawWRS=WarResetStatus
function WarResetStatus(wid)
if JY.Status==GAME_WMAP and War.Turn then War.koSBTurn=War.Turn end-- 이긴 턴 (엔진은 이긴 뒤에도 턴을 올림)
local v=War.Person and War.Person[wid]
if v and v.live and v.action~=9 and JY.Person[v.id] and JY.Person[v.id][HPK]<=0 then
local e,i=cur()
if e then
War.koSBDown=War.koSBDown or {}
if not War.koSBDown[v.id] then
War.koSBDown[v.id]=true
for k=1,2 do local r=e[k] if r then
if v.enemy then
if r.k=="sweep" then add(k) end
else
if r.k=="noloss" and ours(v.id) then add(k) end
if r.k=="keep" and v.id==r.p then add(k) end
end
end end
end
end
end
return rawWRS(wid)
end
-- 누가 쓰러뜨렸나 (같은 적은 한 번만: 연격은 훅을 두 번 부름)
